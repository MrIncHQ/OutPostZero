import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const privateKeyPath = process.argv[2] ?? 'ModuleSigning/private.pem';
const publicKeyPath = process.argv[3] ?? 'ModuleSigning/public.pem';
const runtimePath = path.resolve('module-packages/process-test/runtime/server.cjs');
const outputPath = path.resolve('src/main/builtin-module-package.ts');
const runtime = fs.readFileSync(runtimePath);
const sha256 = crypto.createHash('sha256').update(runtime).digest('hex').toUpperCase();
const payload = {
  schemaVersion: 1,
  id: 'portable-process-test',
  name: 'Portable Process Test',
  description: 'A tiny loopback service used to prove portable module installation and process control.',
  version: '1.0.0',
  platforms: ['win32'],
  architectures: ['x64'],
  downloadSize: runtime.length,
  installSize: runtime.length,
  ownedDirectories: ['Modules/Installed/portable-process-test'],
  sharedDataDirectories: ['Data/Modules/portable-process-test', 'Logs/Modules'],
  dependencies: [],
  runtimeCommand: { executable: 'host-runtime', args: ['runtime/server.cjs'] },
  healthCheck: { type: 'http', path: '/health', timeoutMs: 5000 },
  networkPolicy: 'loopback-only',
  license: 'Outpost Zero internal test module',
  files: [{ path: 'runtime/server.cjs', size: runtime.length, sha256 }],
};
const signedPayload = Buffer.from(JSON.stringify(payload));
const signature = crypto.sign(null, signedPayload, fs.readFileSync(privateKeyPath, 'utf8'));
const publicKey = fs.readFileSync(publicKeyPath, 'utf8').trim();
const packageEnvelope = {
  schemaVersion: 1,
  signedPayload: signedPayload.toString('base64'),
  signature: signature.toString('base64'),
  files: [{ path: 'runtime/server.cjs', content: runtime.toString('base64') }],
};
const generated = `// Generated by scripts/sign-builtin-module.mjs. Do not edit by hand.\n`
  + `export const MODULE_PACKAGE_PUBLIC_KEY = ${JSON.stringify(publicKey)};\n\n`
  + `export const BUILTIN_PROCESS_TEST_PACKAGE = ${JSON.stringify(packageEnvelope, null, 2)} as const;\n`;
fs.writeFileSync(outputPath, generated, 'utf8');
console.log(JSON.stringify({ outputPath, moduleId: payload.id, version: payload.version, files: payload.files.length, sha256 }, null, 2));
