import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const privateKeyPath = process.argv[2] ?? 'ModuleSigning/private.pem';
const archivePath = path.resolve(process.argv[3] ?? 'VendorCache/kiwix-tools_win-x86_64-3.8.1.zip');
const extractedPath = path.resolve(process.argv[4] ?? 'VendorCache/kiwix-tools-3.8.1');
const samplePath = path.resolve(process.argv[5] ?? 'VendorCache/openzim-small.zim');
const outputPath = path.resolve('src/main/kiwix-package.ts');

function metadata(filePath, relativePath) {
  const content = fs.readFileSync(filePath);
  return {
    path: relativePath,
    size: content.length,
    sha256: crypto.createHash('sha256').update(content).digest('hex').toUpperCase(),
  };
}

const archive = metadata(archivePath, path.basename(archivePath));
const sample = metadata(samplePath, 'openzim-small.zim');
const files = fs.readdirSync(extractedPath, { withFileTypes: true })
  .filter((entry) => entry.isFile())
  .map((entry) => metadata(path.join(extractedPath, entry.name), entry.name))
  .sort((left, right) => left.path.localeCompare(right.path));
const payload = {
  schemaVersion: 1,
  id: 'library-engine',
  name: 'Offline Library Engine',
  version: '3.8.1',
  platform: 'win32',
  architecture: 'x64',
  license: 'GPL-3.0-or-later',
  networkPolicy: 'loopback-only',
  ownedDirectory: 'Modules/Installed/kiwix-engine',
  sharedContentDirectory: 'Content/ZIM',
  executable: 'kiwix-serve.exe',
  archive: {
    ...archive,
    url: 'https://download.kiwix.org/release/kiwix-tools/kiwix-tools_win-x86_64-3.8.1.zip',
  },
  files,
  sampleContent: {
    ...sample,
    url: 'https://raw.githubusercontent.com/openzim/zim-testing-suite/main/data/nons/small.zim',
    title: 'OpenZIM Small Test Library',
  },
};
const signedPayload = Buffer.from(JSON.stringify(payload));
const signature = crypto.sign(null, signedPayload, fs.readFileSync(privateKeyPath, 'utf8'));
const envelope = {
  schemaVersion: 1,
  signedPayload: signedPayload.toString('base64'),
  signature: signature.toString('base64'),
};
fs.writeFileSync(outputPath, `// Generated by scripts/sign-kiwix-package.mjs. Do not edit by hand.\nexport const KIWIX_PACKAGE = ${JSON.stringify(envelope, null, 2)} as const;\n`, 'utf8');
console.log(JSON.stringify({ outputPath, archive, sample, files }, null, 2));
